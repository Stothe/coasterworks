/**
 * The name a guest's `name` code stands for: `first * 32 + last`, so "Aiko Abernathy" is 0 and
 * "Zoe Halloran" is 2047. Throws `RangeError` for anything else.
 */
export function guestName(code: number): string {
  if (!Number.isInteger(code) || code < 0 || code >= FIRST_NAMES.length * LAST_NAMES.length) {
    throw new RangeError(`Guest name code must be an integer from 0 to 2047, got ${code}`);
  }
  const last = code % 32;
  const first = (code - last) / 32;
  return `${FIRST_NAMES[first]} ${LAST_NAMES[last]}`;
}
